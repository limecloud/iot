import test from 'node:test';
import assert from 'node:assert/strict';
import { execFile, spawn } from 'node:child_process';
import { promisify } from 'node:util';
import { readFile, writeFile, stat } from 'node:fs/promises';
import { createWriteStream } from 'node:fs';
import path from 'node:path';
import net from 'node:net';
import { root, freePort, stop, until } from '../tools/dev-stack.mjs';
import { mqttProbe } from './support/mqtt-probe.mjs';

const exec = promisify(execFile);
const manager = path.join(root, 'deploy/nas/manage.py');
const issuer = path.join(root, 'deploy/nas/device_identity.py');
test('NAS 设备 mTLS、CA 隔离、证书身份 ACL、撤销和重新签发', { timeout: 45000 }, async t => {
  const directory = path.join(root, '.dev', `identity-test-${Date.now()}`);
  await exec('python3', [manager, 'init', '--directory', directory, '--origin', 'https://127.0.0.1:18443']);
  const issue = async (device, output) => JSON.parse((await exec('python3', [issuer, 'issue', '--directory', directory, '--device-id', device, '--output', output])).stdout);
  const lamp = path.join(directory, 'lamp'), button = path.join(directory, 'button');
  const identity = await issue('device-lamp', lamp);
  await issue('device-button', button);
  await assert.rejects(issue('gateway', path.join(directory, 'invalid')), error => JSON.parse(error.stdout).error === 'device_not_bound_to_gateway');
  await assert.rejects(issue('device-lamp', path.join(directory, 'duplicate')), error => JSON.parse(error.stdout).error === 'active_certificate_exists_revoke_before_reissue');
  assert.equal((await stat(path.join(lamp, 'private.key'))).mode & 0o777, 0o600);
  const [plainPort, port] = [await freePort(), await freePort()];
  const result = await exec('python3', ['-c', 'import sys; from device_identity import broker_config; print(broker_config(*sys.argv[1:4], int(sys.argv[4]), int(sys.argv[5]), "127.0.0.1"))', path.join(directory, 'config'), path.join(directory, 'secrets'), path.join(directory, 'broker-tls'), String(plainPort), String(port)], { cwd: path.join(root, 'deploy/nas') });
  const configuration = path.join(directory, 'mosquitto.conf'); await writeFile(configuration, result.stdout);
  const launch = async () => {
    const child = spawn(path.join(root, '.dev/tools/mosquitto-build/src/mosquitto'), ['-c', configuration], { stdio: ['ignore', 'pipe', 'pipe'] });
    const log = createWriteStream(path.join(directory, 'broker.log'), { flags: 'a' }); child.stdout.pipe(log); child.stderr.pipe(log); child.on('exit', () => log.end());
    t.after(() => stop(child));
    await until(() => new Promise(resolve => { const socket = net.connect({ host: '127.0.0.1', port }); socket.once('connect', () => { socket.destroy(); resolve(true); }); socket.once('error', () => resolve(false)); }));
    return child;
  };
  let broker = await launch();
  const credentials = async directory => ({ ca: await readFile(path.join(directory, 'ca.crt')), cert: await readFile(path.join(directory, 'device.crt')), key: await readFile(path.join(directory, 'private.key')) });
  const lampOptions = { port, ...await credentials(lamp) };
  await assert.rejects(mqttProbe({ port, ca: lampOptions.ca }));
  await assert.rejects(mqttProbe({ port, ...await credentials(button), ca: await readFile(path.join(directory, 'authority/ca.crt')) }));
  await assert.rejects(mqttProbe({ port, ca: lampOptions.ca, cert: await readFile(path.join(directory, 'tls/server.crt')), key: await readFile(path.join(directory, 'tls/server.key')) }));
  await assert.rejects(mqttProbe({ ...lampOptions, servername: 'incorrect.example' }));
  // 即使 CONNECT 自称 gateway，授权身份仍然只能来自设备证书 CN。
  const client = await mqttProbe({ ...lampOptions, username: 'gateway' }); t.after(() => client.close());
  const own = 'limeiot/v1/space-demo/device-lamp';
  assert.ok([0, 16].includes(await client.publish(own + '/up/hello')));
  assert.equal(await client.publish('limeiot/v1/space-demo/device-button/up/event'), 135);
  assert.equal(await client.publish(own + '/down/command'), 135);
  await client.subscribe('limeiot/v1/space-demo/+/down/+');
  const local = await mqttProbe({ port: plainPort, username: 'gateway', password: (await readFile(path.join(directory, 'secrets/gateway-password'), 'utf8')).trim() }); t.after(() => local.close());
  await local.publish('limeiot/v1/space-demo/device-button/down/command');
  await local.publish(own + '/down/command');
  assert.equal((await client.message()).topic, own + '/down/command');
  await assert.rejects(client.message(250), /mqtt_packet_timeout/);
  client.close(); local.close();
  const revoked = JSON.parse((await exec('python3', [issuer, 'revoke', '--directory', directory, '--serial', identity.serial])).stdout);
  assert.equal(revoked.broker_restart_required, true);
  await stop(broker); broker = await launch();
  await assert.rejects(mqttProbe(lampOptions));
  const valid = await mqttProbe({ port, ...await credentials(button) }); valid.close();
  const replacement = path.join(directory, 'lamp-new'); await issue('device-lamp', replacement);
  const renewed = await mqttProbe({ port, ...await credentials(replacement) }); renewed.close();
});
