import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { setTimeout as delay } from 'node:timers/promises';
import { promisify } from 'node:util';
import test from 'node:test';
import { chromium, expect } from '@playwright/test';
import { until } from '../tools/dev-stack.mjs';
import { base, post, targets, devices, environmentStack, thresholdRule } from './fixtures/zigbee/runtime.mjs';
import { verifyObservationCandidate, verifyObservationOperation, verifyObservationBinding } from '../packages/protocol/observation-bindings.mjs';

test('动态来源经真实NCP查询、CLI绑定、采样联动、撤销与原SQLite重启恢复', { timeout: 90000 }, async t => {
  let browser;
  t.after(async () => browser?.close());
  const { directory, stack, sensor, commands, control, stats } = await environmentStack(t, 1, { dynamic: true, timeoutMs: 1500 });
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(stack.env.LIMEIOT_ENDPOINT);
  await page.getByLabel('所有者凭据', { exact: true }).fill(stack.env.LIMEIOT_TOKEN);
  await page.getByRole('button', { name: '连接家庭网关', exact: true }).click();
  const card = page.getByRole('article', { name: '环境传感器', exact: true });
  await expect(card).toHaveCount(0);
  const candidates = base + '/observation-candidates';
  const query = (index = 0) => ({ coordinator_id: 'home-znp', ieee_address: targets[index], endpoint: 1 });
  const initial = (await stack.request(candidates)).value;
  assert.equal(initial.coordinators.length, 1); assert.deepEqual(initial.items, []);
  assert.equal((await stats()).host_checks, 0);
  assert.equal((await stack.request(base + '/devices/' + devices[0])).status, 404);
  assert.equal((await stack.request(candidates, post({ ...query(), serial: '/dev/ttyUSB0' }))).status, 422);
  assert.equal((await stack.request(candidates.replace('space-demo', 'other'), post(query()))).status, 403);
  assert.equal((await stats()).host_checks, 0);
  const response = await stack.request(candidates, post(query())); assert.equal(response.status, 200);
  const candidate = await verifyObservationCandidate(response.value);
  assert.equal((await stack.request(base + '/devices/' + devices[0])).status, 404, '查询不创建逻辑设备');
  assert.equal((await commands()).length, 0);
  const bindingPath = base + '/devices/' + devices[0] + '/observation-binding';
  const empty = await verifyObservationBinding((await stack.request(bindingPath)).value, devices[0]);
  assert.equal(empty.binding, null);
  const change = { type: 'sources.bind', device_id: devices[0], source: candidate.source, expected_binding_revision: empty.revision, expected_model_revision: candidate.model_revision };
  const input = path.join(directory, 'bind.json'); await writeFile(input, JSON.stringify(change));
  const env = { ...process.env, ...stack.env }; delete env.LIMEIOT_TOKEN_FILE;
  const cli = await promisify(execFile)(process.execPath, ['packages/cli/src/main.mjs', 'invoke', 'observation-changes.create', '--space-id', 'space-demo', '--input', input, '--idempotency-key', 'original-bind', '--state-dir', path.join(directory, 'cli')], { env, timeout: 10000 });
  const { cli: local, ...bound } = JSON.parse(cli.stdout); assert.ok(local.record_file);
  await verifyObservationOperation(bound); assert.equal(bound.status, 'applied');
  const first = await until(async () => { const value = await sensor(); return value.ready && value; });
  assert.equal(first.reported['environment.temperature'].value, 2700); assert.equal(first.session_id, null);
  await expect(card.getByText('27.00 ℃', { exact: true })).toBeVisible();
  assert.equal((await stack.request(base + '/rule-deployments', post(thresholdRule()))).status, 200);
  await until(async () => (await sensor()).state_revision > first.state_revision);
  await control(2900);
  await until(async () => { const list = await commands(); return list.length === 1 && list[0].status === 'confirmed'; });
  const current = await verifyObservationBinding((await stack.request(bindingPath)).value);
  const revoked = await stack.request(base + '/observation-operations', { ...post({ type: 'sources.revoke', device_id: devices[0], expected_binding_revision: current.revision }), headers: { 'Content-Type': 'application/json', 'Idempotency-Key': 'original-revoke' } });
  assert.equal(revoked.status, 200); await verifyObservationOperation(revoked.value); assert.equal(revoked.value.status, 'applied');
  assert.equal((await sensor()).ready, false); assert.equal((await sensor()).reported['environment.temperature'].quality, 'stale');
  await expect(card.getByText('离线', { exact: true })).toBeVisible({ timeout: 3000 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(errors, []);
  await page.screenshot({ path: path.join(directory, 'observation-revoked-mobile.png'), fullPage: true });
  await browser.close(); browser = undefined;
  await delay(200);
  const stopped = (await stats()).samples[targets[0]];
  await delay(1200); assert.equal((await stats()).samples[targets[0]], stopped, '撤销后不继续轮询目标');
  await stack.restartGateway();
  assert.equal((await sensor()).ready, false);
  assert.deepEqual((await stack.request(candidates)).value.items, []);
  const recovered = await stack.request(base + '/observation-operations', { ...post(change), headers: { 'Content-Type': 'application/json', 'Idempotency-Key': 'original-bind' } });
  assert.deepEqual(recovered.value, bound, '候选缓存丢失后返回原决定，不重新绑定');
  assert.equal((await sensor()).ready, false);
  const next = await verifyObservationCandidate((await stack.request(candidates, post(query()))).value);
  const baseline = await verifyObservationBinding((await stack.request(bindingPath)).value);
  const rebound = await stack.request(base + '/observation-operations', { ...post({ ...change, source: next.source, expected_binding_revision: baseline.revision }), headers: { 'Content-Type': 'application/json', 'Idempotency-Key': 'explicit-rebind' } });
  assert.equal(rebound.value.status, 'applied'); await verifyObservationOperation(rebound.value);
  await until(async () => (await sensor()).ready);
  assert.equal((await commands()).length, 1, '重绑的高温首样本不补发旧边沿');
  await control(2700); await until(async () => (await sensor()).reported['environment.temperature'].value === 2700);
  await control(2900); await until(async () => { const list = await commands(); return list.length === 2 && list.every(command => command.status === 'confirmed'); });
  await writeFile(path.join(directory, 'observation-runtime-report.json'), JSON.stringify({ passed: true, dynamic_query_cli_bind_revoke_rebind: true,
    real_rust_serial_sqlite_mqtt: true, query_never_creates_device: true, revoked_polling_stopped: true,
    original_decision_survives_cache_loss: true, restart_no_replay: true, responsive_state_browser: true,
    hardware: false, published: false, full_goal_completed: false }, null, 2) + '\n');
  console.log(JSON.stringify({ report: path.join(directory, 'observation-runtime-report.json') }));
});

test('共享串口候选查询有界且拒绝并发，目标超时后已绑定来源继续采样', { timeout: 45000 }, async t => {
  const { directory, stack, sensor, control, stats } = await environmentStack(t, 1, { dynamic: true, timeoutMs: 1000 });
  const query = index => ({ coordinator_id: 'home-znp', ieee_address: targets[index], endpoint: 1 });
  const pathName = base + '/observation-candidates';
  const first = (await stack.request(pathName, post(query(0)))).value;
  const before = (await stack.request(base + '/devices/' + devices[0] + '/observation-binding')).value;
  const bound = await stack.request(base + '/observation-operations', { ...post({ type: 'sources.bind', device_id: devices[0], source: first.source, expected_model_revision: first.model_revision, expected_binding_revision: before.revision }), headers: { 'Content-Type': 'application/json', 'Idempotency-Key': 'create' } });
  assert.equal(bound.value.status, 'applied'); await until(async () => (await sensor()).ready);
  const initial = await sensor();
  await control(2600, 'timeout', 1);
  const pending = stack.request(pathName, post(query(1)));
  await until(async () => (await stats()).timeout_requests > 0);
  const busy = await stack.request(pathName, post(query(1)));
  assert.equal(busy.status, 429); assert.equal(busy.value.error.code, 'observation_query_busy');
  const expired = await pending; assert.equal(expired.status, 504); assert.equal(expired.value.error.code, 'observation_query_timeout');
  const fresh = await until(async () => { const value = await sensor(); return value.ready && value.state_revision > initial.state_revision && value; });
  assert.equal(fresh.reported['environment.temperature'].quality, 'confirmed');
  await writeFile(path.join(directory, 'observation-query-report.json'), JSON.stringify({ passed: true, busy_rejected: true, query_timeout_bounded: true,
    healthy_source_kept: true, software_ncp: true, hardware: false, full_goal_completed: false }, null, 2) + '\n');
  console.log(JSON.stringify({ report: path.join(directory, 'observation-query-report.json') }));
});
