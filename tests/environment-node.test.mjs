import test from 'node:test';
import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdtemp, readFile, writeFile, stat } from 'node:fs/promises';
import path from 'node:path';
import { chromium, expect } from '@playwright/test';
import Ajv from 'ajv/dist/2020.js';
import { root, startStack, until } from '../tools/dev-stack.mjs';
import { documentDigest } from '../packages/protocol/model-validation.mjs';

const exec = promisify(execFile), base = '/api/v1/spaces/space-demo';
test('三节点：NAS环境身份、SHT30同一C驱动采样、多端只读、原采样过期与恢复', { timeout: 180000 }, async t => {
  const directory = await mkdtemp(path.join(root, '.dev/environment-node-')), nas = path.join(directory, 'nas');
  await exec('python3', ['deploy/nas/manage.py', 'init', '--directory', nas, '--origin', 'https://127.0.0.1:18443', '--with-environment'], { cwd: root });
  const config = JSON.parse(await readFile(path.join(nas, 'config/gateway.json')));
  const model = JSON.parse(await readFile(path.join(root, 'contracts/models/environment.json')));
  const schema = JSON.parse(await readFile(path.join(root, 'contracts/model.schema.json')));
  assert.equal(new Ajv({ strict: true }).compile(schema)(model), true);
  const revision = await documentDigest(model);
  assert.equal(config.devices.find(device => device.device_id === 'device-environment').model_revision, revision);
  assert.equal(config.models.length, 3); assert.equal(config.devices.length, 3);
  assert.equal((await stat(path.join(nas, 'secrets/device-environment-password'))).mode & 0o777, 0o600);
  assert.match(await readFile(path.join(nas, 'config/mqtt-acl'), 'utf8'), /user device-environment\ntopic read limeiot\/v1\/space-demo\/device-environment\/down\/\+/);
  const identity = JSON.parse((await exec('python3', ['deploy/nas/device_identity.py', 'issue', '--directory', nas, '--device-id', 'device-environment', '--output', path.join(directory, 'environment-identity')], { cwd: root })).stdout);
  assert.equal(JSON.parse(await readFile(path.join(identity.output, 'identity.json'))).device_id, 'device-environment');
  const credentials = { owner: (await readFile(path.join(nas, 'secrets/owner-token'), 'utf8')).trim() };
  for (const name of ['gateway', 'lamp', 'button', 'environment']) credentials[name] = (await readFile(path.join(nas, 'secrets/'+(name === 'gateway' ? name : 'device-'+name)+'-password'), 'utf8')).trim();
  const stack = await startStack({ directory: path.join(directory, 'runtime'), firmware: true, environment: true, credentials, gatewayEnv: { LIMEIOT_CONFIG: path.join(nas, 'config/gateway.json') } });
  t.after(() => stack.close());
  const sensor = async () => (await stack.request(base+'/devices/device-environment')).value;
  const first = await until(async () => { const value = await sensor(); return value.ready && value.device_info?.fresh && value; });
  assert.equal(first.ready, true); assert.equal(first.model_revision, revision);
  assert.equal(first.reported['environment.temperature'].value, 2500); assert.equal(first.reported['environment.humidity'].value, 5000);
  assert.equal(first.reported['environment.temperature'].source, 'host-fixture.sht3x');
  assert.equal(first.device_info.device.product_id, 'desk-node-environment-host');
  const initialRevision = first.state_revision, sampled = first.reported['environment.temperature'].observed_at;
  const repeated = await until(async () => { const value = await sensor(); return value.state_revision > initialRevision && value; });
  assert.equal(repeated.reported['environment.temperature'].observed_at, sampled, '发送缓存快照不能延长原采样时间');
  const command = await stack.request(base+'/commands', { method: 'POST', headers: { 'Content-Type': 'application/json', 'Idempotency-Key': 'environment-readonly' }, body: JSON.stringify({ device_id: 'device-environment', model_revision: revision, expires_at: new Date(Date.now()+5000).toISOString(), operation: { type: 'property.set', path: 'environment.temperature', value: 2800 } }) });
  assert.equal(command.status, 422); assert.equal(command.value.error.code, 'property_read_only'); assert.equal((await stack.request(base+'/commands')).value.items.length, 0);
  const cli = await exec(process.execPath, ['packages/cli/src/main.mjs', 'devices', 'list', '--space-id', 'space-demo'], { cwd: root, env: stack.env });
  assert.equal(JSON.parse(cli.stdout).items.length, 3);
  const browser = await chromium.launch({ headless: true, executablePath: process.env.LIMEIOT_BROWSER_EXECUTABLE }); t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(stack.env.LIMEIOT_ENDPOINT);
  await page.getByLabel('所有者凭据', { exact: true }).fill(stack.env.LIMEIOT_TOKEN);
  await page.getByRole('button', { name: '连接家庭网关', exact: true }).click();
  const card = page.getByRole('article', { name: '环境传感器', exact: true });
  await expect(card.getByLabel('温度', { exact: true })).toHaveText('25.00 ℃');
  await expect(card.getByLabel('相对湿度', { exact: true })).toHaveText('50.00 %RH');
  await expect(card.getByRole('button', { name: '设置', exact: true })).toHaveCount(0);
  await page.screenshot({ path: path.join(directory, 'environment-desktop.png'), fullPage: true });
  stack.environment.stdin.write('{"sensor_fault":true}\n');
  const stale = await until(async () => { const value = await sensor(); return value.reported['environment.temperature'].quality === 'stale' && value; }, 20000);
  assert.equal(stale.reported['environment.temperature'].observed_at, sampled);
  await expect(card.getByText('已过期', { exact: true })).toHaveCount(2);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.locator("#home-sidebar").evaluate(element => element.getBoundingClientRect().right)).toBeLessThanOrEqual(0);
  await expect(card.getByLabel('温度', { exact: true })).toHaveText('25.00 ℃');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: path.join(directory, 'environment-mobile-stale.png'), fullPage: true });
  stack.environment.stdin.write('{"sensor_fault":false}\n');
  const recovered = await until(async () => { const value = await sensor(); return value.reported['environment.temperature'].quality === 'confirmed' && value.reported['environment.temperature'].observed_at !== sampled && value; }, 15000);
  assert.equal(recovered.reported['environment.temperature'].value, 2500);
  const nativeEnv = { ...stack.env, LIMEIOT_ENVIRONMENT_CHECK: '1' };
  const swift = await exec('swift', ['run', 'ClientChecks'], { cwd: path.join(root, 'apps/ios'), env: nativeEnv, timeout: 60000 });
  assert.match(swift.stdout, /"environment_integration":"passed"/);
  await writeFile(path.join(directory, 'swift.log'), swift.stdout+swift.stderr);
  const kotlin = await exec('sh', ['gradlew', '--no-daemon', ':core:test', '--tests', '*EnvironmentPropertyTest', '--rerun-tasks'], { cwd: path.join(root, 'apps/android'), env: nativeEnv, timeout: 90000 });
  await writeFile(path.join(directory, 'kotlin.log'), kotlin.stdout+kotlin.stderr);
  await stack.restartGateway();
  await until(async () => (await sensor()).ready);
  const restored = await sensor(); assert.equal(restored.model_revision, revision);
  assert.equal((await stack.request(base+'/commands')).value.items.length, 0);
  assert.deepEqual(errors, []);
  await writeFile(path.join(directory, 'report.json'), JSON.stringify({ passed: true, actual_c_driver: true, real_mqtt_gateway_sqlite: true, nas_profile_and_identity: true, readonly_enforced: true, sample_time_preserved: true, stale_then_recovered: true, cli_and_browser: true, swift_kotlin_actual_http: true, desktop_mobile: true, gateway_restart: true, native_app_runtime: false, hardware: false, hardware_status: '用户要求跳过', physical_claim: false, full_goal_completed: false }, null, 2));
});
