import test from 'node:test';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { chromium, expect } from '@playwright/test';
import { base, post, startActionStack } from './helpers/actions.mjs';

test('网页动作联动：模型选项、参数预演、修改撤销旧预演、多步规则完整展示', { timeout: 90000 }, async t => {
  const stack = await startActionStack(); t.after(() => stack.close());
  const browser = await chromium.launch({ headless: true, executablePath: process.env.LIMEIOT_BROWSER_EXECUTABLE }); t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } }); page.setDefaultTimeout(12000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(stack.env.LIMEIOT_ENDPOINT);
  await page.getByLabel('所有者凭据', { exact: true }).fill(stack.env.LIMEIOT_TOKEN);
  await page.getByRole('button', { name: '连接家庭网关', exact: true }).click();
  await page.getByRole('button', { name: '自动化', exact: true }).click();
  await page.getByLabel('执行', { exact: true }).selectOption('device-lamp/invoke/remote.press');
  const input = page.getByLabel('动作参数（JSON）', { exact: true });
  await input.fill('{'); await expect(page.getByRole('button', { name: '校验并预演', exact: true })).toBeDisabled();
  await input.fill('{"key":"shell"}'); await page.getByRole('button', { name: '校验并预演', exact: true }).click();
  await expect(page.getByRole('button', { name: '启用自动化', exact: true })).toBeDisabled();
  await input.fill('{"key":"home"}'); await page.getByRole('button', { name: '校验并预演', exact: true }).click();
  const enable = page.getByRole('button', { name: '启用自动化', exact: true }); await expect(enable).toBeEnabled();
  assert.equal((await stack.request(base + '/commands')).value.items.length, 0);
  await input.fill('{"key":"back"}'); await expect(enable).toBeDisabled();
  await page.getByRole('button', { name: '校验并预演', exact: true }).click(); await expect(enable).toBeEnabled(); await enable.click();
  const row = page.locator('.deployment').first(); await expect(row).toBeVisible();
  await expect(row).toContainText('remote.press'); await expect(row).toContainText('back');
  await row.getByRole('button', { name: '编辑', exact: true }).click(); await expect(input).toHaveValue('{"key":"back"}'); await expect(enable).toBeDisabled();
  const saved = (await stack.request(base + '/rule-deployments')).value.items[0];
  const multi = { ...saved.rule, id: 'multi-rule', actions: [...saved.rule.actions, { device: 'device-lamp', invoke: { path: 'apps.launch', input: { application_id: 'org.example.player' } } }] };
  assert.equal((await stack.request(base + '/rule-deployments', post(multi))).status, 200);
  await expect(page.locator('.deployment')).toHaveCount(2);
  const multiRow = page.locator('.deployment').filter({ hasText: 'apps.launch' });
  await expect(multiRow.locator('li')).toHaveCount(2); await expect(multiRow.getByRole('button', { name: '编辑', exact: true })).toBeDisabled();
  assert.equal((await stack.request(base + '/commands')).value.items.length, 0);
  await page.screenshot({ path: path.join(stack.directory, 'rules-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(async () => { const rect = await page.locator('aside').boundingBox(); return rect.x + rect.width <= 0; }).toBe(true);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: path.join(stack.directory, 'rules-mobile.png'), fullPage: true });
  assert.deepEqual(errors, []);
  await writeFile(path.join(stack.directory, 'rules-actions-web-result.json'), JSON.stringify({ passed: true, real_gateway: true, strict_parameters: true, no_commands_before_event: true, changed_input_requires_simulation: true, action_edit_roundtrip: true, multi_step_no_truncation: true, desktop_mobile_layout: true, native_app_runtime: false, hardware: false }));
});
