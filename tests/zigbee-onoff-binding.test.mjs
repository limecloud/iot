import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import test from 'node:test';
import { chromium, expect } from '@playwright/test';
import { until } from '../tools/dev-stack.mjs';
import { verifyObservationOperation } from '../packages/protocol/observation-bindings.mjs';
import { base, environmentStack } from './fixtures/zigbee/runtime.mjs';

test('网页发现开关后明确授权，丢响应只查询，撤销及重启重绑不补发旧命令', { timeout: 180000 }, async t => {
  const { directory, stack, switchDevice, switchControl, commands, stats } = await environmentStack(t, 1, { dynamic: true, onOff: true, timeoutMs: 1500 });
  const browser = await chromium.launch({ headless: true }); t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block' });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const panel = page.getByRole('region', { name: 'Zigbee设备接入', exact: true });
  const review = panel.getByRole('group', { name: '核对Zigbee设备', exact: true });
  let posts = 0, lost;
  page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith('/observation-operations')) posts++; });
  async function login() {
    await page.goto(stack.env.LIMEIOT_ENDPOINT + '/?view=models');
    await page.getByLabel('所有者凭据', { exact: true }).fill(stack.env.LIMEIOT_TOKEN);
    await page.getByRole('button', { name: '连接家庭网关', exact: true }).click();
    await expect(panel.getByRole('button', { name: '发现已有设备', exact: true })).toBeEnabled();
  }
  await page.goto(stack.env.LIMEIOT_ENDPOINT); await login();
  assert.equal((await stack.request(base + '/devices/zigbee-switch')).status, 404);
  await panel.getByRole('button', { name: '发现已有设备', exact: true }).click();
  const neighbor = panel.getByRole('group', { name: '发现的Zigbee设备', exact: true }).getByRole('article').filter({ hasText: '1122334455667789' });
  await neighbor.getByRole('button', { name: '读取端点', exact: true }).click();
  await panel.getByRole('group', { name: 'Zigbee设备端点', exact: true }).getByRole('button', { name: '查询此端点', exact: true }).click();
  await expect(review.getByText('接入权限：读取和控制电源', { exact: true })).toBeVisible();
  await panel.getByLabel('设备编号', { exact: true }).fill('zigbee-switch');
  // 输入变化使发现失效，手填查询也必须选择明确的固定映射。
  await panel.getByRole('combobox', { name: /^设备类型/ }).selectOption('on_off');
  await panel.getByRole('button', { name: '查询设备', exact: true }).click();
  await expect(review.getByText('Switch-1', { exact: true })).toBeVisible();
  await expect(review.getByText('接入权限：读取和控制电源', { exact: true })).toBeVisible();
  assert.equal(posts, 0); assert.deepEqual((await stats()).switch_commands, []);
  await panel.getByRole('combobox', { name: /^设备类型/ }).selectOption('environment');
  await expect(review).toHaveCount(0);
  await panel.getByRole('combobox', { name: /^设备类型/ }).selectOption('on_off');
  await panel.getByRole('button', { name: '查询设备', exact: true }).click();
  await expect(review).toBeVisible();
  await page.route('**/observation-operations', async route => {
    const response = await route.fetch();
    lost = { key: route.request().headers()['idempotency-key'], operation: await response.json() };
    await route.abort('failed');
  }, { times: 1 });
  await review.getByRole('button', { name: '确认添加设备', exact: true }).click();
  await until(() => lost);
  await verifyObservationOperation(lost.operation);
  assert.deepEqual(lost.operation.result.binding.write_paths, ['light.power']);
  const record = panel.locator(`[data-observation-key="${lost.key}"]`);
  await panel.getByText('接入操作记录', { exact: true }).click();
  await expect(record.getByText('结果未知', { exact: true })).toBeVisible();
  await record.getByRole('button', { name: '查询原操作', exact: true }).click();
  await expect(record.getByText('已完成', { exact: true })).toBeVisible();
  assert.equal(posts, 1);
  await until(async () => (await switchDevice()).ready);
  await page.goto(stack.env.LIMEIOT_ENDPOINT + '/?view=devices');
  const row = panel.locator('[data-observation-device="zigbee-switch"]');
  const card = page.locator('article.device').filter({ has: page.getByText('zigbee-switch', { exact: true }) });
  const toggle = card.getByRole('switch', { name: '电源', exact: true });
  await expect(toggle).toHaveAttribute('aria-checked', 'false'); await toggle.click();
  await until(async () => (await commands()).length === 1 && (await commands())[0].status === 'confirmed');
  await expect(toggle).toHaveAttribute('aria-checked', 'true');
  await switchControl('hold', false);
  await expect(toggle).toHaveAttribute('aria-checked', 'false');
  await expect(toggle).toBeEnabled(); await toggle.click();
  const held = await until(async () => (await commands()).find(command => command.evidence?.type === 'property_adapter_result'));
  assert.equal(held.status, 'dispatched'); assert.equal((await switchDevice()).reported['light.power'].value, false);
  await page.goto(stack.env.LIMEIOT_ENDPOINT + '/?view=models');
  await row.getByRole('button', { name: '撤销接入', exact: true }).click();
  await panel.getByRole('button', { name: '确认撤销接入', exact: true }).click();
  await expect(row.getByText('已撤销', { exact: true })).toBeVisible();
  await until(async () => (await stack.request(base + '/commands/' + held.command_id)).value.status === 'unknown');
  assert.equal((await switchDevice()).ready, false); assert.equal(Object.hasOwn(await switchDevice(), 'routes'), false);
  await page.goto(stack.env.LIMEIOT_ENDPOINT + '/?view=devices');
  await expect(toggle).toBeDisabled();
  await stack.restartGateway(); await expect(page.getByLabel('所有者凭据', { exact: true })).toBeVisible(); await login();
  await expect(row.getByText('已撤销', { exact: true })).toBeVisible();
  assert.equal((await switchDevice()).ready, false); assert.deepEqual((await stats()).switch_commands, [true, true]);
  await row.getByRole('button', { name: '重新接入', exact: true }).click();
  await expect(review.getByText('接入权限：读取和控制电源', { exact: true })).toBeVisible();
  await review.getByRole('button', { name: '确认重新接入', exact: true }).click();
  await until(async () => (await switchDevice()).ready);
  await switchControl('normal', true);
  await until(async () => (await switchDevice()).reported['light.power'].value === true);
  assert.equal((await stack.request(base + '/commands/' + held.command_id)).value.status, 'unknown');
  assert.deepEqual((await stats()).switch_commands, [true, true]);
  assert.equal(posts, 3);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(errors, []); assert.deepEqual((await stats()).errors, []);
  await page.screenshot({ path: path.join(directory, 'dynamic-switch-390.png'), fullPage: true });
  const reportFile = path.join(directory, 'dynamic-switch-report.json');
  await writeFile(reportFile, JSON.stringify({ passed: true, hardware: false, dynamic_switch: true, explicit_write_authority: true,
    response_loss_original_get: true, control_independent_readback: true, revoke_closes_inflight: true,
    revoked_restart_and_explicit_rebind: true, unknown_no_replay: true, binding_posts: posts, native_app_runtime: false }, null, 2) + '\n');
  console.log(JSON.stringify({ report: reportFile }));
});
