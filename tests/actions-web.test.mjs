import test from 'node:test';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { chromium, expect } from '@playwright/test';
import { actionState, base, startActionStack } from './helpers/actions.mjs';

test('网页遥控动作、执行阶段与丢响应恢复：存储失败零发送，桌面及手机布局', { timeout: 90000 }, async t => {
  const stack = await startActionStack(); t.after(() => stack.close());
  const browser = await chromium.launch({ headless: true, executablePath: process.env.LIMEIOT_BROWSER_EXECUTABLE }); t.after(() => browser.close());
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } }), page = await context.newPage();
  page.setDefaultTimeout(12000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const posts = []; page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith(base + '/commands')) posts.push(request.postDataJSON()); });
  await page.goto(stack.env.LIMEIOT_ENDPOINT);
  await page.getByLabel('所有者凭据', { exact: true }).fill(stack.env.LIMEIOT_TOKEN);
  await page.getByRole('button', { name: '连接家庭网关', exact: true }).click();
  const tv = page.getByRole('article', { name: '电视', exact: true });
  await expect(tv.getByRole('group', { name: '遥控器' })).toBeVisible();
  await page.evaluate(() => { const set = Storage.prototype.setItem; Storage.prototype.setItem = function (key, value) { if (key === 'limeiot.pending') throw new DOMException('denied', 'QuotaExceededError'); return set.call(this, key, value); }; });
  await tv.getByRole('button', { name: '主页', exact: true }).click();
  await expect(page.getByText('无法保存本地操作记录，请检查浏览器存储设置', { exact: true })).toBeVisible();
  assert.equal(posts.length, 0);
  assert.equal((await stack.request(base + '/commands')).value.items.length, 0);
  await page.reload();
  await tv.getByRole('button', { name: '主页', exact: true }).click();
  await expect(tv.getByText('最近操作：输入已提交', { exact: true })).toBeVisible();
  assert.deepEqual(posts[0].operation, { type: 'action.invoke', path: 'remote.press', value: { key: 'home' } });
  await tv.getByLabel('应用标识', { exact: true }).fill('org.example.player');
  await tv.getByRole('button', { name: '启动应用', exact: true }).click();
  await expect.poll(async () => (await actionState(stack)).action_log.length).toBe(2);
  await page.getByRole('button', { name: '执行记录', exact: true }).click();
  await expect(page.getByText('遥控：主页', { exact: true })).toBeVisible();
  await expect(page.getByText('启动应用：org.example.player', { exact: true })).toBeVisible();
  assert.equal(await page.getByText('[object Object]', { exact: false }).count(), 0);
  const rows = page.locator('.activity-row'); await expect(rows).toHaveCount(2);
  await expect(rows.locator('.command-status').first()).toHaveText('输入已提交');
  await rows.first().getByText('操作详情', { exact: true }).click();
  await expect(rows.first().getByText('已收到', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '设备', exact: true }).click();
  let lostRequest;
  await page.route('**' + base + '/commands', async route => {
    if (route.request().method() !== 'POST') { await route.continue(); return; }
    lostRequest = route.request().postDataJSON();
    await route.fetch(); await route.abort('failed');
  });
  await tv.getByRole('button', { name: '返回', exact: true }).click();
  await expect(page.getByText('操作结果尚未确认，请查询原操作', { exact: true })).toBeVisible();
  assert.deepEqual(lostRequest.operation, { type: 'action.invoke', path: 'remote.press', value: { key: 'back' } });
  await page.unroute('**' + base + '/commands');
  assert.equal(posts.length, 3);
  await page.reload();
  await expect(tv.getByRole('button', { name: '查询原操作', exact: true })).toBeVisible();
  await page.route('**' + base + '/commands/by-key/*', route => route.fulfill({ status: 404, contentType: 'application/json', body: JSON.stringify({ error: { code: 'command_not_found' } }) }));
  await tv.getByRole('button', { name: '查询原操作', exact: true }).click();
  await expect(page.getByText('尚未查到原操作，请稍后再次查询', { exact: true })).toBeVisible();
  await expect(tv.getByRole('button', { name: '主页', exact: true })).toBeDisabled();
  assert.equal(posts.length, 3);
  await page.unroute('**' + base + '/commands/by-key/*');
  await tv.getByRole('button', { name: '查询原操作', exact: true }).click();
  await expect(tv.getByRole('button', { name: '查询原操作', exact: true })).toHaveCount(0);
  await expect(tv.getByRole('button', { name: '主页', exact: true })).toBeEnabled();
  assert.equal(posts.length, 3); assert.equal((await actionState(stack)).action_log.length, 3);
  await page.screenshot({ path: path.join(stack.directory, 'remote-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const up = await tv.getByRole('button', { name: '上', exact: true }).boundingBox(), left = await tv.getByRole('button', { name: '左', exact: true }).boundingBox();
  assert(up.x > left.x && up.y < left.y); assert(up.height >= 44);
  await page.screenshot({ path: path.join(stack.directory, 'remote-mobile.png'), fullPage: true });
  assert.deepEqual(errors, []);
  await writeFile(path.join(stack.directory, 'actions-web-result.json'), JSON.stringify({ passed: true, real_gateway: true, real_mqtt: true, browser: 'Chromium', storage_failure_zero_posts: true, submitted_scope: true, original_request_recovery: true, missing_original_no_repost: true, desktop_mobile_layout: true, posts: posts.length, hardware: false }));
});
